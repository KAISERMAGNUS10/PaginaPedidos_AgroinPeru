-- 3. Solicitudes de recuperación de contraseña
CREATE TABLE IF NOT EXISTS tbl_solicitudes_recuperacion (
  id_solicitud INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario INT NOT NULL,
  estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
  fecha_solicitud TIMESTAMPTZ DEFAULT NOW(),
  id_soporte INT DEFAULT NULL,
  fecha_atencion TIMESTAMPTZ DEFAULT NULL,
  observacion VARCHAR(255) DEFAULT NULL,
  CONSTRAINT fk_solrec_usuario FOREIGN KEY (id_usuario)
    REFERENCES tbl_usuarios (id_usuario) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_solrec_soporte FOREIGN KEY (id_soporte)
    REFERENCES tbl_usuarios (id_usuario) ON DELETE SET NULL ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_solrec_estado ON tbl_solicitudes_recuperacion (estado);
-- Un usuario solo puede tener una solicitud PENDIENTE a la vez.
CREATE UNIQUE INDEX IF NOT EXISTS uq_solrec_pendiente
  ON tbl_solicitudes_recuperacion (id_usuario) WHERE estado = 'PENDIENTE';
COMMENT ON TABLE tbl_solicitudes_recuperacion IS 'Solicitudes de recuperación de contraseña atendidas por soporte';
COMMENT ON COLUMN tbl_solicitudes_recuperacion.estado IS 'PENDIENTE / ATENDIDA / RECHAZADA';
ALTER TABLE tbl_solicitudes_recuperacion ENABLE ROW LEVEL SECURITY;

